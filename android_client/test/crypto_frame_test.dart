import 'dart:async';
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';
import 'package:zproxy_client/core/crypto_frame.dart';

Uint8List _hexToBytes(String hex) {
  final bytes = Uint8List(hex.length ~/ 2);
  for (var i = 0; i < bytes.length; i++) {
    bytes[i] = int.parse(hex.substring(i * 2, i * 2 + 2), radix: 16);
  }
  return bytes;
}

void main() {
  final vectorsJson = jsonDecode(File('test/vectors/frames.json').readAsStringSync())
      as Map<String, dynamic>;
  final token = vectorsJson['token'] as String;
  final key = keyFor(token);

  group('golden vectors (Python -> Dart compatibility)', () {
    test('decrypts vectors generated by the Python client', () {
      for (final v in vectorsJson['vectors'] as List) {
        final frame = _hexToBytes((v as Map)['frame_hex'] as String);
        final payload = _hexToBytes(v['payload_hex'] as String);
        expect(decryptFrame(frame, key), payload);
      }
    });

    test('key derivation matches Python _key_for (known digest)', () {
      // HMAC-SHA256(b"z-proxy-dev", b"z-proxy:enc:v1")
      expect(
        keyFor('z-proxy-dev'),
        _hexToBytes(
            '95e32339594ad33f3a870ad04d8c8e02f5ac9df9c3d102315b227098b51b8a5b'),
      );
    });
  });

  group('encrypt/decrypt roundtrip', () {
    test('roundtrip arbitrary payloads', () {
      final payloads = [
        Uint8List(0),
        Uint8List.fromList([0x5A, 0x00, 0xFF]),
        Uint8List.fromList(List.filled(1000, 7)),
        utf8.encode('{"m":"CONNECT","t":"example.com:443"}'),
      ];
      for (final p in payloads) {
        final frame = encryptFrame(p, key);
        expect(frame[0], magicByte);
        expect(decryptFrame(frame, key), p);
      }
    });

    test('nonce differs on every encryption', () {
      final f1 = encryptFrame(utf8.encode('same payload'), key);
      final f2 = encryptFrame(utf8.encode('same payload'), key);
      expect(f1.sublist(5, 21), isNot(f2.sublist(5, 21)));
    });
  });

  group('frame validation', () {
    test('tampered payload byte -> null', () {
      final frame = encryptFrame(utf8.encode('hello world'), key);
      frame[21] ^= 0x01;
      expect(decryptFrame(frame, key), isNull);
    });

    test('tampered tag byte -> null', () {
      final frame = encryptFrame(utf8.encode('hello world'), key);
      frame[frame.length - 1] ^= 0x80;
      expect(decryptFrame(frame, key), isNull);
    });

    test('bad magic -> null', () {
      final frame = encryptFrame(utf8.encode('hello'), key);
      frame[0] = 0x00;
      expect(decryptFrame(frame, key), isNull);
    });

    test('declared length over maxPayload -> null', () {
      final frame = encryptFrame(utf8.encode('hello'), key);
      // set len field to 0x00010000 (65536)
      frame[1] = 0x00;
      frame[2] = 0x01;
      frame[3] = 0x00;
      frame[4] = 0x00;
      expect(decryptFrame(frame, key), isNull);
    });

    test('truncated frame -> null', () {
      final frame = encryptFrame(utf8.encode('hello'), key);
      expect(decryptFrame(frame.sublist(0, frame.length - 1), key), isNull);
    });

    test('empty input -> null', () {
      expect(decryptFrame(Uint8List(0), key), isNull);
    });
  });

  group('readFrame (shared iterator)', () {
    test('reads a frame from a split stream', () async {
      final frame = encryptFrame(utf8.encode('stream test'), key);
      final it = StreamIterator(Stream<List<int>>.fromIterable([
        frame.sublist(0, 3),
        frame.sublist(3, 21),
        frame.sublist(21),
      ]));
      final data = await readFrame(it, key);
      await it.cancel();
      expect(data?.payload, utf8.encode('stream test'));
      expect(data?.rest, isEmpty);
    });

    test('keeps bytes trailing the frame as rest', () async {
      final frame = encryptFrame(utf8.encode('hello'), key);
      final it = StreamIterator(Stream<List<int>>.fromIterable([
        [...frame, 1, 2, 3, 4, 5],
      ]));
      final data = await readFrame(it, key);
      await it.cancel();
      expect(data?.payload, utf8.encode('hello'));
      expect(data?.rest, [1, 2, 3, 4, 5]);
    });

    test('returns null on EOF before header', () async {
      final it = StreamIterator(Stream<List<int>>.fromIterable([
        [0x5A, 0x00],
      ]));
      final payload = await readFrame(it, key);
      await it.cancel();
      expect(payload, isNull);
    });

    test('returns null on EOF mid-body', () async {
      final frame = encryptFrame(utf8.encode('hello world'), key);
      final it = StreamIterator(
          Stream<List<int>>.fromIterable([frame.sublist(0, frame.length ~/ 2)]));
      final payload = await readFrame(it, key);
      await it.cancel();
      expect(payload, isNull);
    });

    test('returns null on bad tag', () async {
      final frame = encryptFrame(utf8.encode('hello world'), key);
      frame[frame.length - 1] ^= 0x01;
      final it = StreamIterator(Stream<List<int>>.fromIterable([frame]));
      final payload = await readFrame(it, key);
      await it.cancel();
      expect(payload, isNull);
    });
  });
}